def xorarr(data):
    table = (22, 108, 20, 230, 46, 145, 13, 64, 33, 53, 213, 64,
             19, 3, 233, 128)
    return bytes(byte ^ table[index % len(table)]
                 for index, byte in enumerate(data))


def _crc16_xmodem(data):
    crc = 0
    for byte in data:
        crc ^= byte << 8
        for _ in range(8):
            crc <<= 1
            if crc & 0x10000:
                crc = (crc ^ 0x1021) & 0xFFFF
    return crc & 0xFFFF


def _send_command(serport, data):
    packet = data + struct.pack("<H", _crc16_xmodem(data))
    command = struct.pack(">HBB", 0xABCD, len(data), 0)
    command += xorarr(packet) + struct.pack(">H", 0xDCBA)
    try:
        return serport.write(command)
    except Exception as exc:
        raise errors.RadioError("Error writing data to radio") from exc


def _receive_reply(serport):
    header = serport.read(4)
    if len(header) != 4 or header[:2] != b"\xAB\xCD" or header[3] != 0:
        raise errors.RadioError("Bad response header")
    body = serport.read(header[2])
    if len(body) != header[2]:
        raise errors.RadioError("Command body short read")
    footer = serport.read(4)
    if len(footer) != 4 or footer[2:] != b"\xDC\xBA":
        raise errors.RadioError("Bad response footer")
    return xorarr(body)


def _get_string(data, begin, maxlen):
    result = []
    for byte in data[begin:begin + maxlen]:
        if byte < 0x20 or byte > 0x7E:
            break
        result.append(chr(byte))
    return "".join(result)


def _say_hello(serport):
    hello = b"\x14\x05\x04\x00\x6a\x39\x57\x64"
    for _ in range(5):
        _send_command(serport, hello)
        reply = _receive_reply(serport)
        if reply:
            if reply.startswith(b"\x18\x05"):
                raise errors.RadioError("Radio is in programming mode")
            return _get_string(reply, 4, 24)
    raise errors.RadioError("Failed to initialize radio")


def _read_memory(serport, offset, length):
    command = b"\x1b\x05\x08\x00"
    command += struct.pack("<HBB", offset, length, 0)
    command += b"\x6a\x39\x57\x64"
    _send_command(serport, command)
    reply = _receive_reply(serport)
    data = reply[8:]
    if len(data) != length:
        raise errors.RadioError("Memory read length mismatch")
    return data


def _write_memory(serport, offset, data):
    if len(data) == 0 or len(data) % 8:
        raise errors.RadioError("Memory writes must be a multiple of 8 bytes")
    command = b"\x1d\x05"
    command += struct.pack("<BBHBB", len(data) + 8, 0, offset,
                           len(data), 1)
    command += b"\x6a\x39\x57\x64" + data
    _send_command(serport, command)
    reply = _receive_reply(serport)
    if len(reply) < 6 or reply[0] != 0x1E or reply[4:6] != struct.pack(
            "<H", offset):
        raise errors.RadioError("Bad response to memory write")


def _read_external(serport, address, length):
    if length <= 0:
        return b""
    result = bytearray()
    offset = 0
    while offset < length:
        block_length = min(EXTERNAL_BLOCK, length - offset)
        command = struct.pack(
            "<HHIB3xI", 0x0531, 12, address + offset, block_length,
            EXTERNAL_SESSION_TIMESTAMP)
        _send_command(serport, command)
        reply = _receive_reply(serport)
        if (len(reply) < 12 + block_length or
                struct.unpack_from("<H", reply, 0)[0] != 0x0532 or
                struct.unpack_from("<I", reply, 4)[0] != address + offset or
                reply[8] != block_length):
            raise errors.RadioError("Bad response to external flash read")
        result.extend(reply[12:12 + block_length])
        offset += block_length
    return bytes(result)


def _write_external_once(serport, address, data):
    if len(data) == 0 or len(data) > EXTERNAL_BLOCK:
        raise errors.RadioError("External flash writes must be 1..128 bytes")
    command = struct.pack(
        "<HHIBBHI", 0x0533, 12 + len(data), address, len(data), 1, 0,
        EXTERNAL_SESSION_TIMESTAMP) + data
    _send_command(serport, command)
    reply = _receive_reply(serport)
    if (len(reply) < 12 or
            struct.unpack_from("<H", reply, 0)[0] != 0x0534 or
            struct.unpack_from("<I", reply, 4)[0] != address or
            reply[8] != len(data) or reply[9] != 0):
        raise errors.RadioError("External flash write rejected")


def _write_external_verified(serport, address, data):
    for offset in range(0, len(data), EXTERNAL_BLOCK):
        block = data[offset:offset + EXTERNAL_BLOCK]
        last_error = None
        for _attempt in range(EXTERNAL_WRITE_RETRIES):
            try:
                _write_external_once(serport, address + offset, block)
                if _read_external(
                        serport, address + offset, len(block)) == block:
                    break
            except errors.RadioError as exc:
                last_error = exc
        else:
            message = "External flash readback failed at 0x{:06X}".format(
                address + offset)
            if last_error is not None:
                raise errors.RadioError(message) from last_error
            raise errors.RadioError(message)


def _ensure_external_font(serport):
    if JAPANESE_FONT_SIZE <= 0:
        raise errors.RadioError("Japanese font manifest is missing")
    font_data = _load_japanese_font_data()
    if len(font_data) != JAPANESE_FONT_SIZE:
        raise errors.RadioError("Japanese font binary size does not match the manifest")
    try:
        current = _read_external(serport, JAPANESE_FONT_BASE, len(font_data))
    except errors.RadioError as exc:
        raise errors.RadioError(
            "Japanese font transfer requires the JpRxOnly firmware with "
            "external-flash support") from exc
    if current != font_data:
        _write_external_verified(serport, JAPANESE_FONT_BASE, font_data)


def _decode_name_record(record):
    payload = bytes(record).split(b"\x00", 1)[0].split(b"\xFF", 1)[0]
    if not payload:
        return ""
    try:
        return payload.decode("utf-8")
    except UnicodeDecodeError:
        return ""


def _validate_japanese_name(name):
    try:
        encoded_name = name.encode("utf-8")
    except UnicodeEncodeError as exc:
        raise errors.RadioError("Channel name is not valid UTF-8") from exc

    if len(encoded_name) > JAPANESE_NAME_PAYLOAD_MAX:
        raise errors.RadioError("Channel name exceeds 31 UTF-8 bytes")

    pixel_width = 0
    for character in name:
        codepoint = ord(character)
        if codepoint < 0x20 or codepoint > 0x7E:
            if codepoint not in JAPANESE_CODEPOINTS:
                raise errors.RadioError(
                    "Channel name character U+{:04X} is not in the Japanese font".format(codepoint))
            pixel_width += 16
        else:
            pixel_width += 8
    if pixel_width > 95:
        raise errors.RadioError("Channel name exceeds the LCD display width")
    return encoded_name


def _reset_radio(serport):
    _send_command(serport, b"\xDD\x05\x00\x00")


def _download(radio):
    serport = radio.pipe
    serport.timeout = 0.5
    status = chirp_common.Status()
    status.cur = 0
    status.max = radio.PROFILE.image_size
    status.msg = "Downloading RX-only image"
    radio.status_fn(status)
    firmware = _say_hello(serport)
    if firmware:
        radio.FIRMWARE_VERSION = firmware

    image = bytearray(radio.PROFILE.image_size)
    for offset in range(0, radio.PROFILE.image_size, MEM_BLOCK):
        data = _read_memory(serport, offset, min(
            MEM_BLOCK, radio.PROFILE.image_size - offset))
        image[offset:offset + len(data)] = data
        status.cur = offset + len(data)
        radio.status_fn(status)
    return memmap.MemoryMapBytes(bytes(image))


def _rounded_upload_end(end):
    return (end + 7) & ~7


def _upload(radio):
    serport = radio.pipe
    serport.timeout = 0.5
    status = chirp_common.Status()
    status.cur = 0
    status.max = sum(_rounded_upload_end(end) - start
                     for start, end in radio.PROFILE.upload_ranges)
    status.msg = "Uploading RX-only image"
    radio.status_fn(status)
    firmware = _say_hello(serport)
    if firmware:
        radio.FIRMWARE_VERSION = firmware

    if radio._supports_external_japanese():
        status.msg = "Checking Japanese font support"
        radio.status_fn(status)
        # Probe the custom external-flash command before changing the normal
        # memory image.  Stock firmware must fail here without a partial upload.
        _ensure_external_font(serport)

    done = 0
    for start, end in radio.PROFILE.upload_ranges:
        offset = start
        limit = _rounded_upload_end(end)
        while offset < limit:
            length = min(MEM_BLOCK, limit - offset)
            if length % 8:
                length -= length % 8
            data = bytes(radio.get_mmap()[offset:offset + length])
            _write_memory(serport, offset, data)
            offset += length
            done += length
            status.cur = done
            radio.status_fn(status)
    if radio._supports_external_japanese():
        if radio._japanese_names_dirty:
            status.msg = "Uploading Japanese channel names"
            radio.status_fn(status)
            _write_external_verified(
                serport, JAPANESE_NAME_BASE, radio._japanese_names)
            radio._japanese_names_dirty = False
    status.msg = "Uploaded RX-only image"
    radio.status_fn(status)
    _reset_radio(serport)


def _u16(data, offset):
    return struct.unpack_from("<H", data, offset)[0]


def _put_u16(data, offset, value):
    struct.pack_into("<H", data, offset, value & 0xFFFF)


class _WRXJPBase(chirp_common.CloneModeRadio):
    BAUD_RATE = 38400
    NEEDS_COMPAT_SERIAL = False
    FIRMWARE_VERSION = ""
    PROFILE = None

    def __init__(self, pipe=None):
        super().__init__(pipe)
        self._japanese_names = bytearray(JAPANESE_NAME_TABLE_SIZE)
        self._japanese_names_dirty = False

    def _supports_external_japanese(self):
        return True

    def _external_name_offset(self, index):
        return index * JAPANESE_NAME_RECORD_SIZE

    def _clear_external_name(self, index):
        if not self._supports_external_japanese():
            return
        offset = self._external_name_offset(index)
        self._japanese_names[offset:offset + JAPANESE_NAME_RECORD_SIZE] = \
            b"\x00" * JAPANESE_NAME_RECORD_SIZE
        self._japanese_names_dirty = True

    def _set_external_name(self, index, encoded):
        offset = self._external_name_offset(index)
        self._japanese_names[offset:offset + JAPANESE_NAME_RECORD_SIZE] = \
            encoded.ljust(JAPANESE_NAME_RECORD_SIZE, b"\x00")
        self._japanese_names_dirty = True

    @classmethod
    def get_prompts(cls):
        prompts = chirp_common.RadioPrompts()
        prompts.experimental = (
            "wrx-jp RX-only driver. Keep a complete download as backup before "
            "uploading. This driver never enables transmission."
        )
        prompts.pre_download = (
            "Turn the radio on, connect the programming cable, and keep the "
            "cable firmly inserted. Download and save the image first."
        )
        prompts.pre_upload = (
            "First install the JpRxOnly firmware for this hardware. Then "
            "upload only an image made for this exact profile; the Japanese "
            "font uses the firmware's external-flash command."
        )
        return prompts

    def _special_names(self):
        result = []
        for index, (low, high) in enumerate(BANDS_WIDE):
            label = "F%d(%g-%gM)" % (index + 1, low, high)
            result.extend((label + "A", label + "B"))
        return result

    def _find_band(self, frequency):
        mhz = frequency / 1000000.0
        for index, (low, high) in enumerate(BANDS_WIDE):
            if low <= mhz <= high:
                return index
        return None

    def _resolve_memory(self, number):
        if isinstance(number, str):
            try:
                return True, self._special_names().index(number)
            except ValueError as exc:
                raise errors.RadioError("Unknown special channel") from exc
        if number < 1 or number > self.PROFILE.memory_channels + self.PROFILE.special_count:
            raise errors.RadioError("Channel number out of range")
        if number <= self.PROFILE.memory_channels:
            return False, number - 1
        return True, number - self.PROFILE.memory_channels - 1

    def _channel_offset(self, special, index):
        if special:
            return self.PROFILE.special_base + index * 16
        return index * 16

    def _attribute_offset(self, special, index):
        attr_index = (self.PROFILE.memory_channels + index // 2
                      if special else index)
        if attr_index >= self.PROFILE.attr_limit:
            raise errors.RadioError("Channel attribute out of range")
        return self.PROFILE.attr_base + attr_index * self.PROFILE.attr_width

    def _name_offset(self, index):
        return self.PROFILE.name_base + index * 16

    def _get_scanlists(self, special, index):
        offset = self._attribute_offset(special, index)
        raw = bytes(self._mmap[offset:offset + self.PROFILE.attr_width])
        if self.PROFILE.attr_width == 2:
            return _u16(raw, 0) >> 8
        return raw[0] >> 5

    def _set_scanlists(self, special, index, value):
        offset = self._attribute_offset(special, index)
        raw = bytearray(self._mmap[offset:offset + self.PROFILE.attr_width])
        value = max(0, min(self.PROFILE.attr_scanlist_max, int(value)))
        if self.PROFILE.attr_width == 2:
            _put_u16(raw, 0, (int.from_bytes(raw, "little") & 0x00FF) |
                     (value << 8))
        else:
            raw[0] = (raw[0] & 0x1F) | (value << 5)
        self._set_mmap_bytes(offset, raw)

    def _set_band(self, special, index, band):
        offset = self._attribute_offset(special, index)
        raw = bytearray(self._mmap[offset:offset + self.PROFILE.attr_width])
        if self.PROFILE.attr_width == 2:
            value = int.from_bytes(raw, "little")
            _put_u16(raw, 0, (value & ~0x07) | (band & 0x07))
        else:
            raw[0] = (raw[0] & ~0x07) | (band & 0x07)
        self._set_mmap_bytes(offset, raw)

    def _get_mmap_u16(self, offset):
        raw = bytes(self._mmap[offset:offset + 2])
        return _u16(raw, 0)

    def _set_mmap_u16(self, offset, value):
        raw = bytearray(self._mmap[offset:offset + 2])
        _put_u16(raw, 0, value)
        self._set_mmap_bytes(offset, raw)

    def _set_mmap_bytes(self, offset, data):
        data = bytes(data)
        setter = getattr(self._mmap, "set", None)
        if setter is not None:
            setter(offset, data)
        else:
            self._mmap[offset:offset + len(data)] = data

    @staticmethod
    def _choice_value(choices, value, default=0):
        try:
            index = int(value)
        except (TypeError, ValueError, InvalidValueError):
            index = default
        return choices[max(0, min(len(choices) - 1, index))]

    @staticmethod
    def _choice_index(value, choices, setting_name):
        text = str(value)
        try:
            return choices.index(text)
        except ValueError as exc:
            raise errors.RadioError(
                "Invalid value for %s: %s" % (setting_name, text)) from exc

    @staticmethod
    def _int_value(value, setting_name, minimum=None, maximum=None):
        try:
            result = int(value)
        except (TypeError, ValueError, InvalidValueError) as exc:
            raise errors.RadioError(
                "Invalid value for %s" % setting_name) from exc
        if minimum is not None and result < minimum:
            raise errors.RadioError("%s is below its minimum" % setting_name)
        if maximum is not None and result > maximum:
            raise errors.RadioError("%s is above its maximum" % setting_name)
        return result

    @staticmethod
    def _bool_value(value):
        try:
            return 1 if int(value) else 0
        except (TypeError, ValueError, InvalidValueError):
            return 1 if bool(value) else 0

    @staticmethod
    def _ascii_value(raw):
        result = []
        for byte in raw:
            if byte in (0x00, 0xFF):
                break
            if not 0x20 <= byte <= 0x7E:
                break
            result.append(chr(byte))
        return "".join(result)

    def _append_list_setting(self, group, name, label, choices, index,
                             default=0):
        group.append(RadioSetting(
            name, label,
            RadioSettingValueList(
                choices, self._choice_value(choices, index, default))))

