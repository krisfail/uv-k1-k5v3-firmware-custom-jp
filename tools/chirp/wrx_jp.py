def _load_japanese_font_manifest():
    if _EMBEDDED_FONT_MANIFEST_ZLIB_BASE64:
        try:
            encoded = base64.b64decode(_EMBEDDED_FONT_MANIFEST_ZLIB_BASE64)
            return json.loads(zlib.decompress(encoded).decode("utf-8"))
        except (binascii.Error, UnicodeDecodeError, ValueError, zlib.error):
            LOG.warning("Embedded Japanese font manifest is invalid")
    try:
        with JAPANESE_FONT_MANIFEST_PATH.open("r", encoding="utf-8") as source:
            return json.load(source)
    except (OSError, ValueError):
        return {
            "flash_base": 0x020000,
            "total_bytes": 0,
            "name_table_base": 0x040000,
            "codepoints": [],
        }


